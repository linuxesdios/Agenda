import 'idioma.dart';

/// Diccionario de traducciones clave → texto, uno por idioma.
///
/// Convención de claves: `seccion.nombre_descriptivo`. Las claves genéricas
/// reutilizadas en toda la app (botones comunes, nombres de estado BuJo,
/// nombres de secciones/paletas) viven en namespaces compartidos
/// (`comun.*`, `estado.*`, `seccion.*`, `paleta.*`) para no repetir la
/// traducción de la misma palabra en cada pantalla.
///
/// Simplificación deliberada: los mensajes de error que interpolan una
/// excepción cruda (`'$e'`) no se traducen — ese texto viene de Dart,
/// plugins o del sistema operativo y no tiene sentido traducirlo a mano.
/// Los volcados de diagnóstico técnico (Historial → Ver contenido,
/// Diagnóstico) tampoco se tradujeron: son texto de depuración para
/// power-users, no parte del flujo principal.
class Traducciones {
  static String t(Idioma idioma, String clave) {
    final mapa = _mapas[idioma];
    return mapa?[clave] ?? _es[clave] ?? clave;
  }

  static const Map<Idioma, Map<String, String>> _mapas = {
    Idioma.es: _es,
    Idioma.en: _en,
    Idioma.ru: _ru,
    Idioma.zh: _zh,
  };

  /// Claves presentes en español pero ausentes en algún otro idioma.
  /// Usado solo en verificación (no se llama en runtime de la app).
  static Map<Idioma, List<String>> clavesFaltantes() {
    final resultado = <Idioma, List<String>>{};
    for (final idioma in [Idioma.en, Idioma.ru, Idioma.zh]) {
      final mapa = _mapas[idioma]!;
      resultado[idioma] =
          _es.keys.where((k) => !mapa.containsKey(k)).toList();
    }
    return resultado;
  }

